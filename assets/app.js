class App extends React.Component {
    constructor(props) { super(props); this.state = { route: routeNow(), menu: false, cart: readJson('bitronix_demo_cart', []), toast: '', order: null }; this.onRoute = this.onRoute.bind(this); this.add = this.add.bind(this); this.update = this.update.bind(this); this.remove = this.remove.bind(this); this.checkout = this.checkout.bind(this); this.toastTimer = null; }
    componentDidMount() { window.addEventListener('hashchange', this.onRoute); document.title = 'Bitronix | Good tech. Better experience.'; }
    componentWillUnmount() { window.removeEventListener('hashchange', this.onRoute); if (this.toastTimer)
        clearTimeout(this.toastTimer); }
    onRoute() { this.setState({ route: routeNow(), menu: false, toast: '', order: null }); window.scrollTo(0, 0); }
    notify(s) { this.setState({ toast: s }); if (this.toastTimer)
        clearTimeout(this.toastTimer); this.toastTimer = setTimeout(() => this.setState({ toast: '' }), 3500); }
    saveCart(cart) { localStorage.setItem('bitronix_demo_cart', JSON.stringify(cart)); this.setState({ cart }); }
    add(id, quantity) { const cart = [...this.state.cart]; const i = cart.findIndex(x => x.id === id); if (i >= 0)
        cart[i] = { ...cart[i], qty: Math.min(20, cart[i].qty + quantity) };
    else
        cart.push({ id, qty: quantity }); this.saveCart(cart); this.notify('Added to your demo cart'); }
    update(id, quantity) { const cart = this.state.cart.map(c => c.id === id ? { ...c, qty: Math.min(20, quantity) } : c).filter(c => c.qty > 0); this.saveCart(cart); }
    remove(id) { this.saveCart(this.state.cart.filter(c => c.id !== id)); }
    checkout() { if (this.state.cart.length === 0)
        return; const ref = 'DEMO-' + Date.now().toString(36).toUpperCase().slice(-6); this.saveCart([]); this.setState({ order: ref }); }
    renderPage() { let r = this.state.route; if (r === '/' || r === '')
        return React.createElement(HomePage, { add: this.add }); if (r.startsWith('/shop/') && !r.includes('?'))
        return React.createElement(ProductPage, { key: r, product: getProduct(r.split('/')[2]), add: this.add }); if (r === '/shop' || r.startsWith('/shop?'))
        return React.createElement(ShopPage, { key: r, route: r, add: this.add }); if (r === '/services')
        return React.createElement(ServicesPage, null); if (r === '/track')
        return React.createElement(TrackPage, null); if (r === '/about')
        return React.createElement(AboutPage, null); if (r === '/contact')
        return React.createElement(ContactPage, null); if (r === '/cart')
        return React.createElement(CartPage, { cart: this.state.cart, update: this.update, remove: this.remove, checkout: this.checkout, order: this.state.order }); return React.createElement(NotFoundPage, null); }
    render() { const count = this.state.cart.reduce((a, c) => a + c.qty, 0); const route = this.state.route; const links = [['Shop', '/shop'], ['Services', '/services'], ['Track repair', '/track'], ['About us', '/about'], ['Contact', '/contact']]; return React.createElement("div", { className: "app-shell" },
        React.createElement("div", { className: "topbar" },
            React.createElement("span", null, "Welcome to the next era of everyday tech."),
            React.createElement("a", { href: "#/shop" },
                "EXPLORE THE COLLECTION ",
                React.createElement(Icon, { name: "arrow-up-right", size: 13 }))),
        React.createElement("header", { className: "site-header" },
            React.createElement("div", { className: "container nav-inner" },
                React.createElement(Logo, null),
                React.createElement("nav", { className: 'main-nav ' + (this.state.menu ? 'nav-open' : ''), "aria-label": "Main navigation" }, links.map(([label, path]) => React.createElement("a", { key: path, href: '#' + path, className: route === path || route.startsWith(path + '/') ? 'nav-active' : '', onClick: () => this.setState({ menu: false }) }, label))),
                React.createElement("div", { className: "nav-actions" },
                    React.createElement("a", { href: "#/cart", className: "cart-nav", "aria-label": 'View cart, ' + count + ' items' },
                        React.createElement(Icon, { name: "shopping-bag", size: 21 }),
                        React.createElement("span", null, "Cart"),
                        count > 0 && React.createElement("b", null, count)),
                    React.createElement("button", { type: "button", className: "mobile-toggle", onClick: () => this.setState({ menu: !this.state.menu }), "aria-label": this.state.menu ? 'Close navigation' : 'Open navigation', "aria-expanded": this.state.menu },
                        React.createElement(Icon, { name: this.state.menu ? 'close' : 'menu', size: 23 }))))),
        this.renderPage(),
        React.createElement(Footer, null),
        this.state.toast && React.createElement("div", { className: "toast", role: "status" },
            React.createElement(Icon, { name: "circle-check", size: 21 }),
            this.state.toast,
            React.createElement("a", { href: "#/cart", onClick: () => this.setState({ toast: '' }) },
                "View cart ",
                React.createElement(Icon, { name: "arrow", size: 15 })))); }
}
